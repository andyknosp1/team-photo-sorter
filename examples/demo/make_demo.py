"""Generate the demo project: illustrated players, no real people.

    python examples/demo/make_demo.py demo-project
    cd demo-project
    tps cluster && tps images && TPS_PASSWORD=lakeview-demo tps build

The players are drawn, not photographed, so the face model would not find
them. Instead of `tps scan`, this script writes the face data directly: every
drawn head gets a bounding box and a synthetic 512-number "face" vector, with
noise that grows as the player gets smaller and farther away, the way real
face vectors get noisier. Everything after that (grouping, thumbnails, the
encrypted site) is the real pipeline.
"""
