def font(size):
    for f in ("DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "Arial Bold.ttf"):
        try:
            return ImageFont.truetype(f, size)
        except OSError:
            pass
    return ImageFont.load_default()


class Person:
    def __init__(self, i, rng, cap, number, team):
        self.i, self.cap, self.number, self.team = i, cap, number, team
        self.skin = SKIN[i % len(SKIN)]
        self.hair = [(40, 28, 20), (90, 60, 30), (180, 140, 80), (20, 20, 20), (120, 70, 40)][i % 5]
        self.guard = (240, 190, 60) if team == "home" else (200, 200, 205)
        v = rng.normal(size=512)
        self.vec = v / np.linalg.norm(v)
        far = rng.normal(size=512)
        far /= np.linalg.norm(far)
        # far-away shots drift towards a second "mode", so some players split into two tiles
        self.far = self.vec * 0.8 + far * 0.6
        self.far /= np.linalg.norm(self.far)


def water(rng, goal):
    im = Image.new("RGB", (W, H))
    d = ImageDraw.Draw(im)
    horizon = int(H * rng.uniform(0.18, 0.3))
    for y in range(horizon):   # deck and wall
        t = y / max(1, horizon)
        d.line([(0, y), (W, y)], fill=(int(214 - 40 * t), int(206 - 40 * t), int(190 - 40 * t)))
    for k in range(rng.integers(6, 14)):   # people in the stands, as soft shapes
        x = rng.uniform(0, W)
        d.ellipse([x - 26, horizon * 0.25, x + 26, horizon * 0.25 + 52],
                  fill=tuple(int(c) for c in rng.integers(60, 200, 3)))
    for y in range(horizon, H):   # water gradient
        t = (y - horizon) / (H - horizon)
        d.line([(0, y), (W, y)], fill=(int(40 + 30 * (1 - t)), int(150 + 40 * (1 - t)), int(200 + 25 * (1 - t))))
    for k in range(70):   # ripples
        y = rng.uniform(horizon + 10, H)
        x = rng.uniform(-200, W)
        amp, ln = rng.uniform(2, 6), rng.uniform(120, 420)
        pts = [(x + s, y + amp * math.sin(s / 28)) for s in range(0, int(ln), 6)]
        d.line(pts, fill=(170, 225, 240), width=2)
    for bead in range(0, W, 26):   # lane rope
        y = horizon + 26 + bead * 0.03
        d.ellipse([bead, y, bead + 20, y + 14], fill=RED if (bead // 26) % 4 < 2 else WHITE)
    if goal:
        gx = int(rng.uniform(150, W - 650))
        gy = horizon - 30
        d.rectangle([gx, gy, gx + 520, gy + 170], outline=WHITE, width=10)
        for k in range(1, 26):
            d.line([(gx + k * 20, gy), (gx + k * 20, gy + 170)], fill=(225, 230, 235), width=1)
        for k in range(1, 9):
            d.line([(gx, gy + k * 20), (gx + 520, gy + k * 20)], fill=(225, 230, 235), width=1)
    return im, horizon


def draw_player(im, p, cx, cy, r, rng, arm=False, ball=False):
    d = ImageDraw.Draw(im)
    # shoulders just under the surface
    d.ellipse([cx - r * 1.9, cy + r * 0.7, cx + r * 1.9, cy + r * 2.0], fill=(30, 90, 130))
    if arm:
        side = rng.choice([-1, 1])
        ax = cx + side * r * 1.5
        d.line([(cx + side * r * 1.1, cy + r * 0.9), (ax, cy - r * 1.8)], fill=p.skin, width=int(r * 0.55))
        if ball:
            br = r * 0.75
            bx, by = ax + side * r * 0.2, cy - r * 2.5
            d.ellipse([bx - br, by - br, bx + br, by + br], fill=(247, 205, 40), outline=(40, 40, 40), width=max(1, int(r * 0.06)))
            d.arc([bx - br, by - br * 0.4, bx + br, by + br * 1.6], 200, 340, fill=(40, 40, 40), width=max(1, int(r * 0.06)))
    d.ellipse([cx - r, cy - r, cx + r, cy + r * 1.1], fill=p.skin)            # face
    d.chord([cx - r * 1.05, cy - r * 1.12, cx + r * 1.05, cy + r * 0.55], 180, 360, fill=p.cap)  # cap
    for s in (-1, 1):                                                     # ear guards
        d.ellipse([cx + s * r * 0.95 - r * 0.32, cy - r * 0.05, cx + s * r * 0.95 + r * 0.32, cy + r * 0.55],
                  fill=p.guard)
    ex = r * 0.38
    for s in (-1, 1):                                                     # eyes and brows
        d.ellipse([cx + s * ex - r * 0.1, cy + r * 0.15, cx + s * ex + r * 0.1, cy + r * 0.32], fill=(35, 30, 30))
        d.line([(cx + s * ex - r * 0.17, cy + r * 0.05), (cx + s * ex + r * 0.15, cy + r * 0.02)], fill=p.hair, width=max(1, int(r * 0.07)))
    d.arc([cx - r * 0.3, cy + r * 0.45, cx + r * 0.3, cy + r * 0.8], 20, 160, fill=(150, 60, 60), width=max(1, int(r * 0.07)))
    f = font(int(r * 0.55))
    txt = p.number
    d.text((cx, cy - r * 0.55), txt, fill=WHITE if p.cap != WHITE else NAVY, font=f, anchor="mm")
    return [cx - r, cy - r * 1.12, cx + r, cy + r * 1.15]


def splash(im, rng, cx, cy, r):
    layer = Image.new("RGBA", im.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    for k in range(rng.integers(8, 20)):
        a = rng.uniform(0, math.tau)
        dist = rng.uniform(r * 0.8, r * 2.6)
        s = rng.uniform(r * 0.08, r * 0.3)
        x, y = cx + math.cos(a) * dist, cy + r * 1.2 - abs(math.sin(a)) * dist * 0.8
        d.ellipse([x - s, y - s, x + s, y + s], fill=(255, 255, 255, int(rng.uniform(120, 220))))
    im.paste(Image.alpha_composite(im.convert("RGBA"), layer).convert("RGB"))


def main(out: Path):
    rng = np.random.default_rng(2026)
    random.seed(2026)
    out.mkdir(parents=True, exist_ok=True)
    home = [Person(i, rng, RED if num == "1" else NAVY, num, "home") for i, (num, _, _) in enumerate(ROSTER)]
    others = [Person(20 + i, rng, WHITE, str(n), "away") for i, n in enumerate((3, 5, 8, 11))]
    people = home + others
    weights = np.array([3.0] + [1.0] * 9 + [0.6] * 4)
    weights /= weights.sum()

    roster = "\n".join(f'[[roster]]\nnumber = "{n}"\nname = "{nm}"\nyear = "{y}"\n' for n, nm, y in ROSTER)
    events = "\n".join(f'[[event]]\nid = "{i}"\ntitle = "{t}"\ndate = {d}\nphotos = "photos/{i}"\n' for i, t, d, _ in EVENTS)
    (out / "team.toml").write_text(CONFIG.format(roster=roster, events=events))
    (out / "logo.svg").write_text(LOGO)
    (out / ".gitignore").write_text(".tps/\nsite/\n")

    k_box = DETECT_SIDE / max(W, H)
    for eid, _, _, n in EVENTS:
        folder = out / "photos" / eid
        folder.mkdir(parents=True, exist_ok=True)
        st = EventStore(out / ".tps", eid)
        for j in range(n):
            name = f"IMG_{j + 1:04d}.JPG"
            focus = people[rng.choice(len(people), p=weights)]
            im, horizon = water(rng, goal=(focus.number == "1" and focus.team == "home") or rng.random() < 0.3)
            # the goalie is mostly photographed up close, in front of the cage
            cast = [focus] + [people[x] for x in rng.choice(len(people), size=rng.integers(0, 3), replace=False)
                              if people[x] is not focus and people[x] is not home[0]]
            faces = []
            for c, p in enumerate(cast):
                near = c == 0 and rng.random() < (0.9 if p is home[0] else 0.75)
                r = rng.uniform(70, 120) if near else rng.uniform(24, 46)
                cx = rng.uniform(r * 2.5, W - r * 2.5)
                cy = rng.uniform(horizon + r * 2.2 + (0 if near else 0), H - r * 2.4) if near else \
                    rng.uniform(horizon + r * 2.5, horizon + (H - horizon) * 0.45)
                arm = rng.random() < (0.6 if p.number == "1" and p.team == "home" else 0.35)
                box = draw_player(im, p, cx, cy, r, rng, arm=arm, ball=arm and rng.random() < 0.6)
                if rng.random() < 0.4:
                    splash(im, rng, cx, cy, r)
                noise = 0.45 if near else 0.75
                base = p.vec if near or rng.random() < 0.5 else p.far
                v = base + rng.normal(size=512) * noise / math.sqrt(512)
                v /= np.linalg.norm(v)
                faces.append({"bbox": [round(b * k_box, 1) for b in box], "det": 0.9,
                              "rel_w": round((box[2] - box[0]) / W, 4), "emb": enc(v)})
            im = im.filter(ImageFilter.GaussianBlur(0.6))
            im.save(folder / name, quality=86)
            st.put(name, faces, W, H)
        st.commit()
        print(f"{eid}: {n} photos")
    print(f"\nDemo project in {out}. Next:\n  cd {out}\n  tps cluster && tps images\n"
          "  TPS_PASSWORD=lakeview-demo tps build")


if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else "demo-project"))
