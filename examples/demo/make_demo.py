    ("2026-09-12-north", "vs North", "2026-09-12", 64),
    ("2026-09-19-south-day-1", "at the South Tournament · Day 1", "2026-09-19", 72),
    ("2026-09-26-westbrook", "vs Westbrook", "2026-09-26", 64),
